"""Compare the performance of the implemented PrefixSpan with that of SPMF."""
import math
import os
import subprocess
import time

import lib
import matplotlib.pyplot as plt
import pandas as pd


def get_absolute_minsup(
        minsup: float,
        transaction_count: int,
        rounding: str="ceil"
    ) -> int:
    """Returns the absolute min support."""
    value = minsup * transaction_count / 100

    if rounding == "ceil":
        return math.ceil(value)
    return math.floor(value)


def get_prefixspan_perf(
        db: list[list[int]],
        minsup: float
    ) -> dict[str, dict|float]:
    """Evaluates the performance of the PrefixSpan implementation."""
    # Convert the items to strings
    converted_db = []
    for sequence in db:
        new_sequence = []
        for item in sequence:
            new_sequence.append(str(item))
        converted_db.append(new_sequence)

    # Calculate the absolute min support
    minsup = get_absolute_minsup(minsup, len(converted_db))

    # Call the function and evaluate the performance
    start_time = time.perf_counter()
    frequent_sequences = lib.prefixspan(converted_db, minsup)
    end_time = time.perf_counter()

    execution_time = end_time - start_time

    # Convert the frequent sequence to int
    converted_fs = {}
    for sequence, support in frequent_sequences.items():
        converted_fs[tuple(int(item) for item in sequence)] = support

    return {
        "frequent_sequences": converted_fs,
        "execution_time": execution_time
    }


def get_spmf_perf(
        input_path: str,
        output_path: str,
        minsup: float,
        jar_path: str
    ) -> dict[str, dict|float]:
    """Evaluates the performance of SPMF PrefixSpan."""
    # Execute the SPMF command
    command = [
        "java",
        "-jar",
        jar_path,
        "run",
        "PrefixSpan",
        input_path,
        output_path,
        f"{minsup}%"
    ]

    start_time = time.perf_counter()
    process = subprocess.run(
        command,
        capture_output=True,
        text=True,
        check=True
    )
    end_time = time.perf_counter()

    total_time = end_time - start_time

    # Get SPMF internal execution time
    output_text = process.stdout + process.stderr
    _, internal_time_str = output_text.split("Total time ~ ")
    internal_time_str, _ = internal_time_str.split(sep="\n", maxsplit=1)
    internal_time_str = internal_time_str.strip()
    internal_time = float(internal_time_str) / 1000

    # Read the frequent sequences generated by SPMF
    frequent_sequences = read_spmf_frequent_sequences(output_path)

    return {
        "frequent_sequences": frequent_sequences,
        "total_execution_time": total_time,
        "internal_execution_time": internal_time
    }


def read_spmf_frequent_sequences(path: str) -> dict[tuple[int, ...], int]:
    """Reads the frequent sequences contained in an SPMF output file."""
    result = {}

    with open(path, encoding="utf-8") as file:
        for line in file:
            line = line.strip()

            if not line or line.startswith(("@", "#", "%")):
                continue

            if "#SUP:" not in line:
                continue

            pattern_str, support_str = line.split("#SUP:")
            pattern = tuple(
                int(item)
                for item in pattern_str.split()
                if item not in ["-1", "-2"]
            )
            support = int(support_str.strip())

            result[pattern] = support

    return result


def make_comparison(
        dataset_name: str,
        input_path: str,
        jar_path: str,
        min_supports: list[float],
        repetition_count: int=3
    ) -> pd.DataFrame:
    """Compare the two implementations for a given dataset."""
    # Read the database and measure reading time
    start_time = time.perf_counter()
    db = lib.read_spmf(input_path)
    end_time = time.perf_counter()

    reading_time = end_time - start_time

    print(f"\nDataset: {dataset_name}")
    print(f"Reading time: {reading_time:.3f} seconds")

    result = []
    os.makedirs("outputs/spmf_output", exist_ok=True)
    for min_support in min_supports:
        output_path = f"outputs/spmf_output/{dataset_name}_{min_support}.txt"

        prefixspan_times = []
        spmf_total_times = []
        spmf_internal_times = []

        prefixspan_patterns = {}
        spmf_patterns = {}
        same_patterns = True

        for _ in range(repetition_count):
            # Run implemented PrefixSpan
            prefixspan_results = get_prefixspan_perf(db, min_support)
            prefixspan_times.append(prefixspan_results["execution_time"])
            prefixspan_patterns = prefixspan_results["frequent_sequences"]

            # Run SPMF
            spmf_results = get_spmf_perf(
                input_path,
                output_path,
                min_support,
                jar_path
            )
            spmf_total_times.append(spmf_results["total_execution_time"])
            spmf_internal_times.append(spmf_results["internal_execution_time"])
            spmf_patterns = spmf_results["frequent_sequences"]

            # Compare the results
            if prefixspan_patterns != spmf_patterns:
                same_patterns = False

        # Calculate mean execution times
        mean_prefixspan_time = sum(prefixspan_times) / len(prefixspan_times)
        mean_spmf_total_time = sum(spmf_total_times) / len(spmf_total_times)
        mean_spmf_internal_time = sum(spmf_internal_times) / len(spmf_internal_times)

        # Count patterns
        prefixspan_patterns_count = len(prefixspan_patterns)
        spmf_patterns_count = len(spmf_patterns)

        # Add a new comparison line to the result
        comparison_line = {
            "dataset": dataset_name,
            "minsup": min_support,
            "absolute_minsup": get_absolute_minsup(min_support, len(db)),
            "prefixspan_time": mean_prefixspan_time,
            "spmf_total_time": mean_spmf_total_time,
            "spmf_internal_time": mean_spmf_internal_time,
            "prefixspan_patterns_count": prefixspan_patterns_count,
            "spmf_patterns_count": spmf_patterns_count,
            "same_patterns": same_patterns,
            "speedup": mean_spmf_internal_time / mean_prefixspan_time
        }

        result.append(comparison_line)

        print(f"\nExecution for minsup={min_support}%:")
        print(f"  - prefixspan={mean_prefixspan_time:.3f}s")
        print(f"  - SPMF={mean_spmf_internal_time:.3f}s")
        print(f"  - prefixspan patterns count={prefixspan_patterns_count}")
        print(f"  - SPMF patterns count={spmf_patterns_count}")
        print(f"  - Same patterns={same_patterns}")

    return pd.DataFrame(result)


def show_performance(
        comparison_df: pd.DataFrame,
        dataset_name: str
    ) -> None:
    """Creates, displays, and saves performance comparison charts."""
    x_data = comparison_df["minsup"]

    # Execution time
    plt.figure(figsize=(7, 5), dpi=300)
    plt.semilogy()

    plt.plot(
        x_data,
        comparison_df["prefixspan_time"],
        marker="o",
        label="Implemented PrefixSpan"
    )

    plt.plot(
        x_data,
        comparison_df["spmf_internal_time"],
        marker="s",
        linestyle="--",
        label="SPMF"
    )

    plt.xlabel("Minimum support (%)")
    plt.ylabel("Execution time (seconds)")
    plt.title(f"Execution time on {dataset_name}")

    plt.gca().invert_xaxis()

    plt.legend()
    plt.grid()

    os.makedirs("outputs/comparison_fig", exist_ok=True)
    plt.savefig(
        f"outputs/comparison_fig/{dataset_name}_execution_time.png"
    )
    plt.show()

    # Number of patterns
    plt.figure(figsize=(7, 5), dpi=300)

    plt.plot(
        x_data,
        comparison_df["prefixspan_patterns_count"],
        marker="o",
        label="Implemented PrefixSpan"
    )

    plt.plot(
        x_data,
        comparison_df["spmf_patterns_count"],
        marker="s",
        linestyle="--",
        label="SPMF"
    )

    plt.xlabel("Minimum support (%)")
    plt.ylabel("Number of patterns")
    plt.title(f"Number of patterns on {dataset_name}")

    plt.gca().invert_xaxis()

    plt.legend()
    plt.grid()

    plt.savefig(
        f"outputs/comparison_fig/{dataset_name}_pattern_count.png"
    )
    plt.show()


def run_make_comparison() -> None:
    """Runs the performance comparison for the SIGN and LEVIATHAN datasets."""
    jar_path = "src/java/spmf.jar"

    sign_results = make_comparison(
        "SIGN",
        "data/SIGN.txt",
        jar_path,
        [70, 60, 50, 45, 40, 35, 30, 25, 20]
    )
    os.makedirs("outputs/comparison_df", exist_ok=True)
    sign_results.to_csv("outputs/comparison_df/sign_results.csv")

    leviathan_results = make_comparison(
        "LEVIATHAN",
        "data/LEVIATHAN.txt",
        jar_path,
        [30, 20, 15, 10, 7.5, 5, 2.5]
    )
    leviathan_results.to_csv("outputs/comparison_df/leviathan_results.csv")


def run_show_performance() -> None:
    """Displays and saves the performance comparison for the datasets."""
    sign_comparison_df = pd.read_csv("outputs/comparison_df/sign_results.csv")
    leviathan_comparison_df = pd.read_csv(
        "outputs/comparison_df/leviathan_results.csv"
    )

    show_performance(sign_comparison_df, "SIGN")
    show_performance(leviathan_comparison_df, "LEVIATHAN")


def print_additional_analyses() -> None:
    """Displays the results of the additional analyses."""
    sign_comparison_df = pd.read_csv("outputs/comparison_df/sign_results.csv")
    leviathan_comparison_df = pd.read_csv(
        "outputs/comparison_df/leviathan_results.csv"
    )
    comparison_df = pd.concat(
        [sign_comparison_df, leviathan_comparison_df],
        ignore_index=True
    )
    comparison_df = comparison_df.drop(columns=comparison_df.columns[0])
    comparison_df.to_csv("outputs/comparison_df/all_results.csv")

    print("Speedup (SPMF / Implemented PrefixSpan)\n")
    print(
        comparison_df[
            ["dataset", "minsup", "speedup"]
        ]
    )

    comparison_df["jvm_overhead"] = (
        comparison_df["spmf_total_time"]
        - comparison_df["spmf_internal_time"]
    )
    comparison_df["jvm_overhead_percent"] = (
        comparison_df["jvm_overhead"]
        / comparison_df["spmf_total_time"]
        * 100
    )
    print("\n\n\nJVM Overhead\n")
    print(
        comparison_df[
            [
                "dataset",
                "minsup",
                "jvm_overhead",
                "jvm_overhead_percent"
            ]
        ]
    )


if __name__ == "__main__":
    run_make_comparison()
    run_show_performance()
    print_additional_analyses()
